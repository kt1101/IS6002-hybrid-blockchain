def _fault_args(fault):
    """veritas flags of a node with an injected fault (None: no flags).

    The fault is armed but never turns on by itself (--fault-after is
    FAULT_AFTER_NEVER); experiments/faults.sh sends SIGUSR1 to the server
    (pid in VERITAS_PIDFILE) at the injection time, which activates it.

    >>> _fault_args("corrupt")
    ' --fault=corrupt --fault-after=87600h'
    """
    if fault is None:
        return ""
    if fault not in NODE_FAULTS:
        raise ValueError("unknown node fault %r (want one of %s)" % (fault, ", ".join(NODE_FAULTS)))
    return " --fault=%s --fault-after=%s" % (fault, FAULT_AFTER_NEVER)


def _batch_flush_arg(batch_flush):
    """veritas flag of a non-default batcher flush interval (None: no flag, the
    binary's default 1 s applies, as in the original code).

    >>> _batch_flush_arg("250ms")
    ' --batch-flush=250ms'
    """
    return "" if batch_flush is None else " --batch-flush=%s" % batch_flush


def _demo_events_arg(demo_events):
    """veritas flag that starts the node observer (live demo; False: no flag).

    >>> _demo_events_arg(True)
    ' --demo-events-addr=:7300'
    """
    return " --demo-events-addr=:%d" % DEMO_EVENTS_PORT if demo_events else ""


def check_batch_flush(batch_flush):
    """Raise ValueError unless batch_flush is None or a positive duration like
    1s, 250ms, 2m, 1h (the forms run_one.sh accepts; Go's ParseDuration reads them)."""
    if batch_flush is None:
        return
    m = re.fullmatch(r"([0-9]+)(ms|s|m|h)", batch_flush)
    if not m or int(m.group(1)) < 1:
        raise ValueError("invalid --batch-flush %r: want a positive duration like 1s, 250ms, 2m" % (batch_flush,))


def _forward_sigterm(start, fault=None, batch_flush=None, extra=""):
    """Lines that start veritas (start ends with ' &') so that SIGTERM/SIGINT
    reaching bash is passed on to it and bash waits for it (core backends:
    the server writes its breakdown on SIGTERM).

    The trap comes first, so no SIGTERM can arrive between the start and the
    trap; until veritas runs the trap only exits. The server's pid is written
    to VERITAS_PIDFILE (the fault injector signals it there). fault (None,
    'silent' or 'corrupt') adds the --fault flags (_fault_args); batch_flush
    (None or a duration) adds --batch-flush (_batch_flush_arg); extra (phase-2
    core flags, core_flags(), plus the live demo's --demo-events-addr,
    _demo_events_arg) is appended as is.
    """
    if not start.endswith(" &"):
        raise ValueError("veritas start line must end with ' &': %r" % (start,))
    return [
        "veritas_pid=",
        "trap 'if [ -n \"$veritas_pid\" ]; then kill -TERM \"$veritas_pid\" 2>/dev/null || true;"
        " wait \"$veritas_pid\" || true; fi; exit 143' TERM INT",
        start[:-2] + _fault_args(fault) + _batch_flush_arg(batch_flush) + extra + " &",
        "veritas_pid=$!",
        "echo \"$veritas_pid\" >%s" % VERITAS_PIDFILE,
    ]


VERIFY_SIGS_MODES = ("none", "ingress", "all")


def core_flags(verify_sigs="none", key_seed=None, attest_every=0, n=None, attest_quorum=0):
    """Phase-2 veritas flags of every core node ("" for the phase-1 defaults).

    >>> core_flags()
    ''
    >>> core_flags("all", "s1")
    ' --verify-sigs=all --key-seed=s1'
    >>> core_flags(attest_every=10, n=4)
    ' --attest-every=10 --n=4'
    >>> core_flags(attest_every=1, n=4, attest_quorum=2)
    ' --attest-every=1 --n=4 --attest-quorum=2'
    """
    if not isinstance(attest_every, int) or attest_every < 0:
        raise ValueError("attest_every must be an integer >= 0, got %r" % (attest_every,))
    if not isinstance(attest_quorum, int) or attest_quorum < 0:
        raise ValueError("attest_quorum must be an integer >= 0, got %r" % (attest_quorum,))
    if attest_quorum > 0 and attest_every == 0:
        raise ValueError("attest_quorum=%d needs attest_every > 0" % attest_quorum)
    if attest_quorum > 0 and (n is None or attest_quorum > n):
        raise ValueError("attest_quorum=%d > n=%r" % (attest_quorum, n))
    if verify_sigs not in VERIFY_SIGS_MODES:
        raise ValueError("verify_sigs must be one of %s, got %r" % (VERIFY_SIGS_MODES, verify_sigs))
    if key_seed is not None and not re.fullmatch(r"[A-Za-z0-9._-]+", key_seed):
        raise ValueError("key_seed must match [A-Za-z0-9._-]+, got %r" % (key_seed,))
    out = ""
    if verify_sigs != "none":
        out += " --verify-sigs=%s" % verify_sigs
    if key_seed is not None:
        out += " --key-seed=%s" % key_seed
    if attest_every > 0:
        out += " --attest-every=%d --n=%d" % (attest_every, n)
    if attest_quorum > 0:
        out += " --attest-quorum=%d" % attest_quorum
    return out


def raft_peers(n):
    """--raft-peers of an n-node raft cluster: node<i>=RAFTADDR/FORWARDADDR.

    >>> raft_peers(2)
    'node1=172.28.0.11:7100/172.28.0.11:7101,node2=172.28.0.12:7100/172.28.0.12:7101'
    """
    return ",".join(
        "node%d=%s:%d/%s:%d" % (j, node_ip(j), RAFT_PORT, node_ip(j), RAFT_FORWARD_PORT)
        for j in range(1, n + 1))


def _raft_node(i, n, block_size, commit_mode, memlimit, fault=None, batch_flush=None, extra=""):
    """Node of the Raft backend (consensus/raft + core.Server).

    Same binary, TSO and redis wiring as kafka, no Kafka. The raft server ID
    is the signature node<i>; the raft log and snapshots live in /data/raft
    (the node's named volume). node1 alone gets --raft-bootstrap (it
    bootstraps the full static peer set; the others wait to be contacted).
    The raft transport binds to all interfaces and advertises the node IP.
    SIGTERM is forwarded as for kafka, so the breakdown reaches /results.
    """
    parties = ",".join("node%d" % j for j in range(1, n + 1))
    return [
        "set -eu",
    ] + REDIS_START + _forward_sigterm(
        "GOMEMLIMIT=%s veritas-kafka --consensus=raft --commit-mode=%s --version-mode=client --node-id=%d"
        " --signature=node%d --parties=%s --blk-size=%d --addr=:%d"
        " --raft-peers=%s --raft-bind=0.0.0.0:%d --raft-dir=/data/raft%s"
        " --redis-addr=127.0.0.1:6379 --redis-db=0 --ledger-path=/data/veritas%d"
        " --breakdown-out=/results/breakdown-node%d.json &"
        % (memlimit, commit_mode, i, i, parties, block_size, VERITAS_PORT,
           raft_peers(n), RAFT_PORT, " --raft-bootstrap" if i == 1 else "", i, i), fault, batch_flush, extra
    ) + _exit_when_any_exits(["redis-server", "veritas-kafka"])


def _tendermint_node(i, n, block_size, commit_mode, memlimit, fault=None, batch_flush=None, extra=""):
    """Node of the Tendermint backend (consensus/tendermint + core.Server).

    Same layout as tm-orig (tendermint home copied from the read-only /tmcfg
    into /data/tm, redis, then the veritas server, then tendermint once the
    ABCI socket listens), but the server is veritas-kafka --consensus=
    tendermint with --version-mode=ordered (no TSO). SIGTERM is forwarded to
    the server as for kafka/raft, so the breakdown reaches /results; the
    server closes its ABCI socket, tendermint is killed with the container.
    """
    parties = ",".join("node%d" % j for j in range(1, n + 1))
    return [
        "set -eu",
        "mkdir -p /data/tm && cp -R /tmcfg/. /data/tm/",
    ] + REDIS_START + _forward_sigterm(
        # GOMEMLIMIT applies to the veritas server only, not to tendermint.
        "GOMEMLIMIT=%s veritas-kafka --consensus=tendermint --commit-mode=%s --version-mode=ordered --node-id=%d"
        " --signature=node%d --parties=%s --blk-size=%d --addr=:%d"
        " --tm-abci-socket=%s --tm-rpc-addr=%s"
        " --redis-addr=127.0.0.1:6379 --redis-db=0 --ledger-path=/data/veritas%d"
        " --breakdown-out=/results/breakdown-node%d.json &"
        % (memlimit, commit_mode, i, i, parties, block_size, VERITAS_PORT,
           TM_ABCI_LISTEN, TM_RPC, i, i), fault, batch_flush, extra
    ) + [
        # tendermint exits if the ABCI app is not listening yet. The wait is
        # bounded (ABCI_WAIT_TRIES x 0.2 s) and stops early if the server
        # died, so a server that never listens shows up as an exited
        # container (health.sh fails fast) instead of a node that hangs.
        "abci_wait=0",
        "until (echo > /dev/tcp/127.0.0.1/26658) 2>/dev/null; do"
        " kill -0 \"$veritas_pid\" 2>/dev/null || { echo 'hbdb: veritas server exited before its ABCI socket listened' >&2; exit 1; };"
        " abci_wait=$((abci_wait + 1));"
        " if [ \"$abci_wait\" -ge %d ]; then echo 'hbdb: ABCI socket 127.0.0.1:26658 not listening after %ds' >&2; exit 1; fi;"
        " sleep 0.2; done" % (ABCI_WAIT_TRIES, ABCI_WAIT_TRIES // 5),
        "tendermint start --home /data/tm --proxy-app=%s &" % TM_ABCI_DIAL,
    ] + _exit_when_any_exits(["redis-server", "veritas-kafka", "tendermint"])


def bft2_peers(n):
    """--peers of an n-replica bft2 cluster: <id>=HOST:PORT, id i = node$i.

    >>> bft2_peers(2)
    '1=172.28.0.11:7200,2=172.28.0.12:7200'
    """
    return ",".join("%d=%s:%d" % (j, node_ip(j), BFT2_PORT) for j in range(1, n + 1))


def _bft2_node(i, n, block_size, commit_mode, memlimit, mem, fault=None, batch_flush=None, extra=""):
    """Node of the bft2 backend (consensus/bft2 + core.Server, HotStuff sidecar).

    redis, then bft2-node (replica i of the static set 1..n, replica server
    on 0.0.0.0:BFT2_PORT, local API on 127.0.0.1:BFT2_API_PORT), then, once
    the local API listens (bounded wait that stops early if bft2-node died),
    veritas-kafka --consensus=bft2 --version-mode=ordered (no TSO). bft2-node
    waits by itself (up to 120 s) for every peer's replica server, then
    connects; if that fails it exits and so does the container. SIGTERM is
    forwarded to veritas as for kafka/raft/tendermint, so the breakdown
    reaches /results; bft2-node is killed with the container. GOMEMLIMIT is
    20% of the node cap for bft2-node (BFT2_GOMEMLIMIT_SHARE) and 70% of the
    rest for the veritas server (bft2_veritas_gomemlimit; 768m -> 153 + 430
    MiB), so both limits fit in the one container. bft2-node exits 3 if its replica can no longer
    commit (it fell behind past its retained blocks), which ends the
    container like any other dead process. fault arms veritas --fault as on
    the other core backends (_forward_sigterm); VERITAS_PIDFILE holds the
    veritas pid, never bft2-node's, so the injector's SIGUSR1 reaches veritas.
    """
    parties = ",".join("node%d" % j for j in range(1, n + 1))
    return [
        "set -eu",
    ] + REDIS_START + [
        "GOMEMLIMIT=%s bft2-node --id=%d --peers=%s --listen=0.0.0.0:%d --api=%s --forward-port=%d &"
        % (gomemlimit(mem, BFT2_GOMEMLIMIT_SHARE), i, bft2_peers(n), BFT2_PORT, BFT2_API_ADDR, BFT2_FORWARD_PORT),
        "bft2_pid=$!",
        "api_wait=0",
        "until (echo > /dev/tcp/127.0.0.1/%d) 2>/dev/null; do"
        " kill -0 \"$bft2_pid\" 2>/dev/null || { echo 'hbdb: bft2-node exited before its local API listened' >&2; exit 1; };"
        " api_wait=$((api_wait + 1));"
        " if [ \"$api_wait\" -ge %d ]; then echo 'hbdb: bft2-node local API 127.0.0.1:%d not listening after %ds' >&2; exit 1; fi;"
        " sleep 0.2; done" % (BFT2_API_PORT, BFT2_API_WAIT_TRIES, BFT2_API_PORT, BFT2_API_WAIT_TRIES // 5),
    ] + _forward_sigterm(
        "GOMEMLIMIT=%s veritas-kafka --consensus=bft2 --commit-mode=%s --version-mode=ordered --node-id=%d"
        " --signature=node%d --parties=%s --blk-size=%d --addr=:%d"
        " --bft2-api=%s"
        " --redis-addr=127.0.0.1:6379 --redis-db=0 --ledger-path=/data/veritas%d"
        " --breakdown-out=/results/breakdown-node%d.json &"
        % (bft2_veritas_gomemlimit(mem), commit_mode, i, i, parties, block_size, VERITAS_PORT, BFT2_API_ADDR, i, i),
        fault, batch_flush, extra
    ) + _exit_when_any_exits(["redis-server", "bft2-node", "veritas-kafka"])


def _tm_orig_node(i, n, block_size, memlimit):
    parties = ",".join("node%d" % j for j in range(1, n + 1))
    return [
        "set -eu",
        # Tendermint home lives in the node's named volume; /tmcfg is the
        # read-only config generated by up.sh (`tendermint testnet`).
        "mkdir -p /data/tm && cp -R /tmcfg/. /data/tm/",
    ] + REDIS_START + [
        # GOMEMLIMIT applies to veritas-tm only, not to tendermint.
        "GOMEMLIMIT=%s veritas-tm --signature=node%d --parties=%s --blk-size=%d --addr=:%d"
        " --redis-addr=127.0.0.1:6379 --redis-db=0 --ledger-path=/data/veritas%d"
        " --tendermint-socket=%s --abci-socket=%s &"
        % (memlimit, i, parties, block_size, VERITAS_PORT, i, TM_ABCI_LISTEN, TM_RPC),
        # tendermint exits if the ABCI app is not listening yet.
        "until (echo > /dev/tcp/127.0.0.1/26658) 2>/dev/null; do sleep 0.2; done",
        "tendermint start --home /data/tm --proxy-app=%s &" % TM_ABCI_DIAL,
    ] + _exit_when_any_exits(["redis-server", "veritas-tm", "tendermint"])


def _kafka_service(cpus=KAFKA_CPUS, mem=KAFKA_MEM):
    s = _service(KAFKA_IMAGE, "kafka", KAFKA_IP, cpus, mem)
    # E5 RTT: experiments/net.sh delays the broker's egress with tc netem too
    # (iproute2 is in Dockerfile.kafka).
    s["cap_add"] = ["NET_ADMIN"]
    s["working_dir"] = "/opt/kafka"
    s["command"] = _bash([
        "set -u",
        "rm -f %s" % KAFKA_READY_FILE,
        "KAFKA_HEAP_OPTS='-Xms256m -Xmx256m' bin/zookeeper-server-start.sh config/zookeeper.properties &",
        "until (echo > /dev/tcp/127.0.0.1/2181) 2>/dev/null; do sleep 0.5; done",
        # Same change as scripts/start_veritas_kafka.sh: advertise the broker IP.
        "KAFKA_HEAP_OPTS='-Xms512m -Xmx512m' bin/kafka-server-start.sh config/server.properties"
        " --override advertised.listeners=PLAINTEXT://%s:%d &" % (KAFKA_IP, KAFKA_PORT),
        "until KAFKA_HEAP_OPTS='-Xmx128m' bin/kafka-topics.sh --create --if-not-exists"
        " --topic %s --bootstrap-server 127.0.0.1:%d; do sleep 1; done" % (KAFKA_TOPIC, KAFKA_PORT),
        "touch %s" % KAFKA_READY_FILE,
        "echo 'hbdb: kafka ready, topic %s exists'" % KAFKA_TOPIC,
        # Exit (and show up in `docker compose ps`) as soon as zk or kafka dies.
        "wait -n",
        "echo 'hbdb: zookeeper or kafka exited' >&2",
        "exit 1",
    ])
    s["healthcheck"] = {
        "test": ["CMD", "test", "-f", KAFKA_READY_FILE],
        "interval": "2s",
        "timeout": "5s",
        "retries": 90,
    }
    return s


def parse_node_faults(items):
    """{node index: fault} from --node-fault values like 'node4=corrupt'.

    >>> parse_node_faults(["node4=corrupt", "node3=corrupt"])
    {4: 'corrupt', 3: 'corrupt'}
    """
    out = {}
    for item in items or ():
        m = re.match(r"^node([1-9][0-9]*)=([a-z]+(?:-[a-z]+)*)$", item)
        if not m:
            raise ValueError("invalid --node-fault %r: want node<i>=<fault>, e.g. node4=corrupt" % (item,))
        i = int(m.group(1))
        if i in out:
            raise ValueError("--node-fault: node%d given twice" % i)
        out[i] = m.group(2)
    return out


def check_node_faults(backend, n, node_faults):
    """Raise ValueError unless node_faults ({index: fault}) fits the cluster:
    core backends only, known faults, silent only for kafka (the other
    backends have no vote hook: their F2 is network-level), nodes 1..n."""
    if not node_faults:
        return
    if backend not in CORE_BACKENDS:
        raise ValueError("node faults need a core backend (%s), got %s" % (", ".join(CORE_BACKENDS), backend))
    for i, fault in sorted(node_faults.items()):
        if not 1 <= i <= n:
            raise ValueError("node fault for node%d, but n=%d" % (i, n))
        if fault not in NODE_FAULTS:
            raise ValueError("unknown node fault %r for node%d (want one of %s)" % (fault, i, ", ".join(NODE_FAULTS)))
        if fault == "silent" and backend != "kafka":
            raise ValueError("node fault silent needs backend kafka (veritas --fault=silent), got %s" % backend)


def gen(backend, n, block_size, commit_mode, cpus, mem,
        tm_dir=None, ycsb_dir=None, results_dir=None, node_faults=None, batch_flush=None,
        kafka_cpus=KAFKA_CPUS, kafka_mem=KAFKA_MEM, verify_sigs="none", key_seed=None, attest_every=0,
        attest_quorum=0, publish_ports=False):
    """Return the compose document (a dict) for one cluster.

    commit_mode is accepted for every backend; the original backends have a
    fixed behaviour (kafka-orig async, tm-orig sync) and ignore it; the new
    backends pass it to the server as --commit-mode.
    tm_dir is the `tendermint testnet` output (node0..node{n-1}), mounted
    read-only into node1..nodeN (tm-orig and tendermint).
    node_faults ({node index: 'silent' | 'corrupt'}) arms veritas --fault on
    those nodes (see _fault_args; core backends only, silent only for kafka).
    batch_flush (None or a duration like "250ms") sets veritas --batch-flush,
    the core batcher's flush interval, on every node of a core backend; None
    leaves the flag out (the binary's default, 1 s). The original backends
    have no such flag.
    kafka_cpus / kafka_mem are the Kafka broker's caps (default 2 CPUs,
    1536m as in phase 1). verify_sigs / key_seed are the phase-2 veritas
    --verify-sigs / --key-seed of every core node (core_flags).
    publish_ports (live demo, off by default: the output is then unchanged)
    publishes on 127.0.0.1 of the host every node's gRPC port and observer
    port (HOST_GRPC_BASE + i, HOST_EVENTS_BASE + i) and the TSO's, and starts
    the observer (veritas --demo-events-addr) on the core backends; the
    original backends have no observer, so only their ports are published.
    """
    if backend not in ALL_BACKENDS:
        raise ValueError("unknown backend %r" % backend)
    if backend not in IMPLEMENTED:
        raise NotImplementedError("backend %s not implemented yet" % backend)
    if n < 1:
        raise ValueError("n must be >= 1")
    if block_size < 1:
        raise ValueError("block_size must be >= 1")
    if commit_mode not in COMMIT_MODES:
        raise ValueError("commit_mode must be one of %s" % (COMMIT_MODES,))
    memlimit = gomemlimit(mem)
    gomemlimit(kafka_mem)  # validates the broker's memory cap
    if not kafka_cpus > 0:
        raise ValueError("kafka_cpus must be > 0, got %r" % (kafka_cpus,))
    node_faults = dict(node_faults or {})
    check_node_faults(backend, n, node_faults)
    check_batch_flush(batch_flush)
    extra = core_flags(verify_sigs, key_seed, attest_every, n, attest_quorum)
    # Flags of the core backends' veritas: phase 2 and 3 plus the demo observer.
    node_extra = extra + _demo_events_arg(publish_ports)
    if extra and backend not in CORE_BACKENDS:
        raise ValueError("--verify-sigs/--key-seed need a core backend (%s), got %s" % (", ".join(CORE_BACKENDS), backend))
    if batch_flush is not None and backend not in CORE_BACKENDS:
        raise ValueError("--batch-flush needs a core backend (%s), got %s" % (", ".join(CORE_BACKENDS), backend))

    gen_dir = os.path.join(REPO_ROOT, "experiments", "cluster", "generated")
    tm_dir = os.path.abspath(tm_dir or os.path.join(gen_dir, "tm"))
    ycsb_dir = os.path.abspath(ycsb_dir or os.path.join(REPO_ROOT, "results", "ycsb"))
    results_dir = os.path.abspath(results_dir or os.path.join(REPO_ROOT, "results", "raw"))

    services = {}
    volumes = {}

    if uses_kafka(backend):
        services["kafka"] = _kafka_service(kafka_cpus, kafka_mem)

    if uses_tso(backend):
        tso = _service(NODE_IMAGE, "tso", TSO_IP, TSO_CPUS, TSO_MEM)
        tso["cap_add"] = ["NET_ADMIN"]  # E5 RTT: net.sh delays the TSO's egress too
        tso["working_dir"] = "/data"  # the oracle writes orc.log into its cwd
        tso["command"] = ["veritas-tso", "--addr=:%d" % TSO_PORT]
        tso["volumes"] = ["tso-data:/data"]
        if publish_ports:
            tso["ports"] = ["127.0.0.1:%d:%d" % (HOST_TSO_PORT, TSO_PORT)]
        volumes["tso-data"] = {}
        services["tso"] = tso

    for i in range(1, n + 1):
        name = "node%d" % i
        s = _service(NODE_IMAGE, name, node_ip(i), cpus, mem)
        s["cap_add"] = ["NET_ADMIN"]
        vol = "%s-data" % name
        volumes[vol] = {}
        s["volumes"] = ["%s:/data" % vol]
        if backend == "kafka-orig":
            s["command"] = _bash(_kafka_orig_node(i, n, block_size, memlimit))
            s["depends_on"] = {"kafka": {"condition": "service_healthy"}}
        elif backend == "kafka":
            s["command"] = _bash(_kafka_node(i, n, block_size, commit_mode, memlimit, node_faults.get(i), batch_flush, node_extra))
            s["depends_on"] = {"kafka": {"condition": "service_healthy"}}
            s["volumes"].append("%s:/results" % results_dir)
        elif backend == "raft":
            s["command"] = _bash(_raft_node(i, n, block_size, commit_mode, memlimit, node_faults.get(i), batch_flush, node_extra))
            s["volumes"].append("%s:/results" % results_dir)
        elif backend == "tendermint":
            s["command"] = _bash(_tendermint_node(i, n, block_size, commit_mode, memlimit, node_faults.get(i), batch_flush, node_extra))
            s["volumes"].append("%s:/tmcfg:ro" % os.path.join(tm_dir, "node%d" % (i - 1)))
            s["volumes"].append("%s:/results" % results_dir)
        elif backend == "bft2":
            s["command"] = _bash(_bft2_node(i, n, block_size, commit_mode, memlimit, mem, node_faults.get(i), batch_flush, node_extra))
            s["volumes"].append("%s:/results" % results_dir)
        elif backend == "tm-orig":
            s["command"] = _bash(_tm_orig_node(i, n, block_size, memlimit))
            s["volumes"].append("%s:/tmcfg:ro" % os.path.join(tm_dir, "node%d" % (i - 1)))
        if publish_ports:
            s["ports"] = ["127.0.0.1:%d:%d" % (HOST_GRPC_BASE + i, VERITAS_PORT),
                          "127.0.0.1:%d:%d" % (HOST_EVENTS_BASE + i, DEMO_EVENTS_PORT)]
        services[name] = s

    client = _service(NODE_IMAGE, "client", CLIENT_IP, CLIENT_CPUS, CLIENT_MEM)
    client["command"] = ["sleep", "infinity"]
    client["volumes"] = [
        "client-data:/data",
        "%s:/ycsb:ro" % ycsb_dir,
        "%s:/results" % results_dir,
    ]
    volumes["client-data"] = {}
    services["client"] = client

    return {
        "name": PROJECT,
        "networks": {NETWORK: {"driver": "bridge", "ipam": {"config": [{"subnet": SUBNET}]}}},
        "volumes": volumes,
        "services": services,
    }


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--backend", required=True, choices=ALL_BACKENDS)
    p.add_argument("--n", type=int, required=True, help="number of veritas nodes")
    p.add_argument("--block-size", type=int, default=100)
    p.add_argument("--commit-mode", default="sync", choices=COMMIT_MODES)
    p.add_argument("--cpus", type=float, default=0.5, help="CPU cap per node")
    p.add_argument("--mem", default="768m", help="memory cap per node")
    p.add_argument("--out", default="-", help="output file ('-' = stdout)")
    p.add_argument("--tm-dir", default=None, help="tendermint testnet dir (tm-orig, tendermint)")
    p.add_argument("--ycsb-dir", default=None, help="YCSB data dir, mounted at /ycsb in client")
    p.add_argument("--results-dir", default=None, help="results dir, mounted at /results in client")
    p.add_argument("--node-fault", action="append", default=[], metavar="NODE=FAULT",
                   help="arm veritas --fault on a node, e.g. node4=corrupt (repeatable; core backends;"
                        " silent: kafka only)")
    p.add_argument("--batch-flush", default=None, metavar="DURATION",
                   help="veritas --batch-flush (batcher flush interval, e.g. 250ms) on every node of a core"
                        " backend; default: flag left out (veritas default 1s)")
    p.add_argument("--kafka-cpus", type=float, default=KAFKA_CPUS,
                   help="CPU cap of the Kafka broker container (kafka-orig, kafka)")
    p.add_argument("--kafka-mem", default=KAFKA_MEM, help="memory cap of the Kafka broker container")
    p.add_argument("--verify-sigs", default="none", choices=VERIFY_SIGS_MODES,
                   help="veritas --verify-sigs of every core node (phase 2)")
    p.add_argument("--key-seed", default=None, help="veritas --key-seed of every core node (default: flag left out)")
    p.add_argument("--attest-every", type=int, default=0,
                   help="veritas --attest-every (and --n) of every core node (phase 2; 0: off)")
    p.add_argument("--attest-quorum", type=int, default=0,
                   help="veritas --attest-quorum of every core node (phase 3; 0: veritas' default 2f+1)")
    p.add_argument("--publish-ports", action="store_true",
                   help="live demo: publish node gRPC/observer ports and the TSO on 127.0.0.1 of the host and"
                        " start the node observer (veritas --demo-events-addr) on core backends")
    a = p.parse_args(argv)

    cpus = int(a.cpus) if a.cpus == int(a.cpus) else a.cpus
    kafka_cpus = int(a.kafka_cpus) if a.kafka_cpus == int(a.kafka_cpus) else a.kafka_cpus
    try:
        doc = gen(a.backend, a.n, a.block_size, a.commit_mode, cpus, a.mem,
                  tm_dir=a.tm_dir, ycsb_dir=a.ycsb_dir, results_dir=a.results_dir,
                  node_faults=parse_node_faults(a.node_fault), batch_flush=a.batch_flush,
                  kafka_cpus=kafka_cpus, kafka_mem=a.kafka_mem,
                  verify_sigs=a.verify_sigs, key_seed=a.key_seed, attest_every=a.attest_every,
                  attest_quorum=a.attest_quorum, publish_ports=a.publish_ports)
    except NotImplementedError as e:
        sys.stderr.write("gen_compose: %s\n" % e)
        return 2
    except ValueError as e:
        sys.stderr.write("gen_compose: %s\n" % e)
        return 1

    text = json.dumps(doc, indent=2, sort_keys=False) + "\n"
    if a.out == "-":
        sys.stdout.write(text)
    else:
        tmp = a.out + ".tmp"
        with open(tmp, "w") as f:
            f.write(text)
        os.replace(tmp, a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
